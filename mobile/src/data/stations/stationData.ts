export const ALL_STATIONS: Station[] = (() => {
  const map = new Map<string, Station>();
  PURPLE_LINE.forEach((s) => map.set(s.id, { ...s }));
  GREEN_LINE.forEach((s) => {
    if (map.has(s.id)) {
      const existing = map.get(s.id)!;
      existing.line = 'both';
      existing.is_interchange = true;
    } else {
      map.set(s.id, { ...s });
    }
  });
  return Array.from(map.values());
})();

export function getStationName(id: string): string {
  const s = ALL_STATIONS.find((st) => st.id === id);
  return s ? s.name : id;
}

export function getStationById(id: string): Station | undefined {
  return ALL_STATIONS.find((st) => st.id === id);
}

export function getStationLine(id: string): string {
  const s = ALL_STATIONS.find((st) => st.id === id);
  return s ? s.line : 'purple';
}
